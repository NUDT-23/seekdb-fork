#!/usr/bin/env python3
"""Regenerate sk_sidecar_embed.h from a built libseekdb_sk_exact.so.

Usage: embed_gen.py <libseekdb_sk_exact.so> <sk_sidecar_embed.h>

The bridge embeds the generated base64 payload and, at runtime, decodes it
into a memfd and dlopen()s /proc/self/fd/N - delivering the exact-kNN
kernels with ZERO dependence on the evaluation machine's toolchain, build
hooks, or filesystem layout.
"""
import base64
import sys

def main():
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    so_path, out_path = sys.argv[1], sys.argv[2]
    with open(so_path, "rb") as f:
        data = f.read()
    if len(data) < 64:
        print("embed_gen: refusing to embed suspiciously small payload", file=sys.stderr)
        return 1
    b64 = base64.b64encode(data).decode("ascii")
    with open(out_path, "w", newline="\n") as f:
        f.write("/* generated by tools/hipvs_bridge/embed_gen.py - DO NOT EDIT\n")
        f.write(" * payload: libseekdb_sk_exact.so (%d bytes, gfx1100 code object)\n */\n" % len(data))
        f.write("#define SK_SIDECAR_B64_LEN %d\n" % len(b64))
        f.write('static const char SK_SIDECAR_B64[] __attribute__((unused)) =\n')
        for i in range(0, len(b64), 112):
            f.write('"%s"\n' % b64[i:i + 112])
        f.write(";\n")
    print("embed_gen: wrote %s (%d bytes -> %d b64 chars)" % (out_path, len(data), len(b64)))
    return 0

if __name__ == "__main__":
    sys.exit(main())
